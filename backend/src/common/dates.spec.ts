import { addDays, eachNight, nightsBetween, overlaps } from './dates';

describe('dates', () => {
  it('рахує ночі', () => {
    expect(nightsBetween('2026-12-01', '2026-12-04')).toBe(3);
  });
  it('перелічує ночі проживання', () => {
    expect(eachNight('2026-12-30', '2027-01-02')).toEqual(['2026-12-30', '2026-12-31', '2027-01-01']);
  });
  it('додає дні', () => {
    expect(addDays('2026-02-28', 1)).toBe('2026-03-01');
  });
  it('перевіряє перетин бронювань', () => {
    expect(overlaps('2026-12-01', '2026-12-03', '2026-12-02', '2026-12-05')).toBe(true);
    // виїзд в день заїзду іншого гостя — не конфлікт
    expect(overlaps('2026-12-01', '2026-12-03', '2026-12-03', '2026-12-05')).toBe(false);
  });
});
